-- Read-only identity for the dq-triage agent. Run once in Snowsight as ACCOUNTADMIN.
-- Before running: replace <PASTE_PUBLIC_KEY_HERE> with the body of
-- ~/.snowflake/pagila_triage_rsa_key.pub (lines between BEGIN/END, joined into one line).

USE ROLE USERADMIN;

CREATE ROLE IF NOT EXISTS PAGILA_TRIAGE
    COMMENT = 'Read-only: SELECT on PAGILA_MIG for the dq-triage agent';

-- Grants come from SECURITYADMIN, which holds MANAGE GRANTS (needed for future grants).
USE ROLE SECURITYADMIN;
GRANT ROLE PAGILA_TRIAGE TO ROLE SYSADMIN;
GRANT USAGE ON WAREHOUSE PAGILA_WH TO ROLE PAGILA_TRIAGE;
GRANT USAGE ON DATABASE PAGILA_MIG TO ROLE PAGILA_TRIAGE;

-- Existing objects, plus future ones: the loader and fault restore recreate tables,
-- and dbt recreates views, so SELECT must carry over to new objects.
GRANT USAGE ON SCHEMA PAGILA_MIG.RAW TO ROLE PAGILA_TRIAGE;
GRANT SELECT ON ALL TABLES IN SCHEMA PAGILA_MIG.RAW TO ROLE PAGILA_TRIAGE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA PAGILA_MIG.RAW TO ROLE PAGILA_TRIAGE;

GRANT USAGE ON SCHEMA PAGILA_MIG.STAGING TO ROLE PAGILA_TRIAGE;
GRANT SELECT ON ALL VIEWS IN SCHEMA PAGILA_MIG.STAGING TO ROLE PAGILA_TRIAGE;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA PAGILA_MIG.STAGING TO ROLE PAGILA_TRIAGE;

GRANT USAGE ON SCHEMA PAGILA_MIG.MARTS TO ROLE PAGILA_TRIAGE;
GRANT SELECT ON ALL TABLES IN SCHEMA PAGILA_MIG.MARTS TO ROLE PAGILA_TRIAGE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA PAGILA_MIG.MARTS TO ROLE PAGILA_TRIAGE;

GRANT USAGE ON SCHEMA PAGILA_MIG.QA TO ROLE PAGILA_TRIAGE;
GRANT SELECT ON ALL TABLES IN SCHEMA PAGILA_MIG.QA TO ROLE PAGILA_TRIAGE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA PAGILA_MIG.QA TO ROLE PAGILA_TRIAGE;

-- Service user. No secondary roles, so a session can never pick up PAGILA_ROLE's writes.
USE ROLE USERADMIN;

CREATE USER IF NOT EXISTS PAGILA_TRIAGE_SVC
    TYPE = SERVICE
    DEFAULT_ROLE = PAGILA_TRIAGE
    DEFAULT_WAREHOUSE = PAGILA_WH
    DEFAULT_NAMESPACE = PAGILA_MIG.RAW
    DEFAULT_SECONDARY_ROLES = ()
    RSA_PUBLIC_KEY = '<PASTE_PUBLIC_KEY_HERE>'
    COMMENT = 'dq-triage agent, read-only';

ALTER USER PAGILA_TRIAGE_SVC SET STATEMENT_TIMEOUT_IN_SECONDS = 60;

USE ROLE SECURITYADMIN;
GRANT ROLE PAGILA_TRIAGE TO USER PAGILA_TRIAGE_SVC;

-- Verify
SHOW GRANTS TO ROLE PAGILA_TRIAGE;
SHOW FUTURE GRANTS IN SCHEMA PAGILA_MIG.RAW;
DESC USER PAGILA_TRIAGE_SVC;
